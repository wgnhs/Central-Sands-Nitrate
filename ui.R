            misuse or misrepresentation of the data."),
          p("The app was created using R statistical programming and Shiny programming that visualize MODPATH output and Wiscland data. 
          It was created by the WGNHS with input and review by staff at UW–Madison Division of Extension and Portage County.")
          )
        ),
        fluidRow(
          box(width = 8, h2("Questions"), "For questions about the app, contact ", tags$b("Dave Hart")," (djhart@wisc.edu) at WGNHS or" , 
          tags$b("Jennifer McNelly")," (jennifer.mcnelly@wisc.edu) at Wood County Extension.")
        ),
        fluidRow(
          box(width = 8, h2("How to Use"), "Select the ", tags$b("Interactive Map")," tab above to bring up a map of the Central Sands. 
              Then select a point within the gray outline of the Central Sands to see predicted flow paths, land cover, and transit times.")
        ),
        fluidRow(
          box(width = 8, h2("Disclaimer"), "This representation of flow paths, land use, and transit times in the Central Sands of Wisconsin is provided by the WGNHS on an as is basis. 
