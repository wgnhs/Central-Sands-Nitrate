  dashboardHeader(disable = TRUE),
  dashboardSidebar(disable = TRUE),
  dashboardBody(
    tags$head(
      tags$script(HTML("
          $(document).keyup(function(event) {
            if (event.keyCode == 13) { // 13 is the Enter key code
              $('#password_submit').click(); // Replace 'myActionButton' with your button's inputId
            }
          });
        "))
    ),
    tabsetPanel(
      id = "mainPanel",

      #First tab - Purpose and Disclaimer----
      tabPanel(
        title = "Purpose and Disclaimer",
        fluidRow(
          box(width = 8, h2("Purpose"), 
          p("The", tags$b("Central Sands Groundwater Tracker")," is a web application (app) designed by the Wisconsin Geologic 
