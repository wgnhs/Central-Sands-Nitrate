            groundwater in Wisconsin’s Central Sands."),
          p("The app was created as an educational tool and can be used to: (1) identify contributing areas for groundwater in a 
            given area, (2) understand how long groundwater may take to travel to a given area, (3) identify the land cover at the 
            start of an identified groundwater flow path, and (4) inform how long it may take for changes in land use or management
            to impact groundwater in a given area."),
          p("The app does not identify which groundwater flow paths are accessed by any specific well. The app also does not 
            inform users of how land use along a groundwater flow path may affect the water quality."),
          p("The app is only a representation of groundwater flow in the Central Sands generated by a computer model of groundwater 
            flow for the region (see the ", tags$b("Model Assumptions")," tab for more information). It is not applicable outside of the model 
