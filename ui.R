              and vertical groundwater flow. Flow paths that start farther away from the discharge point move deeper while 
              those starting nearer the discharge point are shallower. The longer and deeper flow paths take more time to 
              reach their discharge points and so that groundwater is generally older. The shorter and shallower flow paths 
              take less time to reach their discharge points and so that groundwater is generally younger."),
          ),
        fluidRow(
          column(width = 6, imageOutput("groundWaterImage"),"Figure courtesy of the U.S. Geologic Survey. 
                 Source: https://doi.org/10.3133/fs06301.")
        )
        ),
      
      #Fourth tab - Additional Info----
      tabPanel(
        title = "Additional Resources",
        fluidRow(
          box(htmlOutput("externalLinks"))
        ),
        fluidRow(
          box(width = 6, h2("General Questions"), "For questions and more information about groundwater in the Central Sands, 
          contact ", tags$b("Dave Hart")," (djhart@wisc.edu) at WGNHS or " , tags$b("Jennifer McNelly")," (jennifer.mcnelly@wisc.edu)
          at Wood County Extension"),
        )
      )     
      
    )
    ),
